"""The application configuration header a bundle exports (ironside_bundle_config.h).

The header carries the base configuration an App is built against: the partition
sizes and the PSA key slot storage size that place the App in NVM and RAM. Both
are write-once UICR words, so a device keeps them for its lifetime. It carries
nothing from UROT's image configuration (the non-secure watchdog, the DFU
triggers): a UROT update can change that, and would leave a value compiled into
the App stale. ld preprocesses the header too, so it holds plain integer
literals only, with no suffixes or includes.
"""

from __future__ import annotations

from . import parts, psa_key_ram, uicr

HEADER_NAME = "ironside_bundle_config.h"
# Where build.py exports the header, relative to the sample's build directory.
BUILD_SUBDIR = "bundle-config"


def values(soc: str | None, partitions_kb: dict, key_slot_storage_size: int) -> dict:
    """The configuration a device provisioned with these settings applies.

    @key_slot_storage_size is the base configuration's PSA key slot storage size.
    """
    return {
        "soc": soc,
        "partitions_kb": {name: partitions_kb[name] for name in uicr.PARTITION_NAMES},
        "key_slot_storage_size": key_slot_storage_size,
    }


def render(cfg: dict, source: str) -> str:
    """The header text for @cfg (from values()); @source names the bundle it came from."""
    p = cfg["partitions_kb"]
    lines = [
        "/*",
        f" * Generated by ironside_bundle.py export-config from {source}.",
        " * Regenerate it when the bundle's configuration changes; do not edit it.",
        " */",
        "",
        "#ifndef IRONSIDE_BUNDLE_CONFIG_H",
        "#define IRONSIDE_BUNDLE_CONFIG_H",
        "",
    ]
    if cfg["soc"] is not None:
        macro = parts.by_soc(cfg["soc"]).mdk_macro
        lines += [
            f"#if !defined({macro})",
            f'#error "{HEADER_NAME} is for the {cfg["soc"]}; build the App for that SoC"',
            "#endif",
            "",
        ]
    blocks = {name: uicr.kb_to_blocks(p[name], name, allow_zero=True) for name in uicr.PARTITION_NAMES}
    lines += [
        "/* UICR.IRONSIDE.IROT.PARTITIONS: the NVM partition sizes the device is",
        f" * provisioned with, in {uicr.PARTITION_BLOCK_KB} KB blocks. */",
        f"#define IRONSIDE_BASECONF_PARTITIONS_SLOT1_SIZE4KB     {blocks['slot1']}",
        f"#define IRONSIDE_BASECONF_PARTITIONS_APPSTORAGE_SIZE4KB  {blocks['appstorage']}",
        f"#define IRONSIDE_BASECONF_PARTITIONS_UROTSTORAGE_SIZE4KB {blocks['urotstorage']}",
        f"#define IRONSIDE_BASECONF_PARTITIONS_DFUIMAGE_SIZE4KB    {blocks['dfuimage']}",
        "",
        "/* UICR.IRONSIDE.UROT.KEYSLOTSTORAGESIZE: the PSA key slot storage size in",
        " * bytes, the base slots at the top of ROT-RAM included; where it ends places",
        " * the non-secure RAM base. It holds "
        f"{psa_key_ram.psa_key_slots(cfg['key_slot_storage_size'])} slots. */",
        f"#define IRONSIDE_BASECONF_KEYSLOTSTORAGESIZE {cfg['key_slot_storage_size']}",
        "",
        "#endif /* IRONSIDE_BUNDLE_CONFIG_H */",
        "",
    ]
    return "\n".join(lines)


def reference() -> dict:
    """The configuration of a bundle that sets nothing, with the reference partitions."""
    return values(
        None,
        dict(zip(uicr.PARTITION_NAMES, uicr.REFERENCE_PARTITIONS_KB, strict=True)),
        psa_key_ram.KEY_SLOT_STORAGE_SIZE_MIN,
    )
